function applyLanguage(lang) {
  const dict = translations[lang] || translations.en;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const val = dict[key];
    if (val == null) return;

    const isHtml = el.getAttribute("data-i18n-html") === "true";
    if (isHtml) el.innerHTML = val;
    else el.textContent = val;
  });

  document.documentElement.lang = translations[lang] ? lang : "en";
  try { localStorage.setItem("lang", lang); } catch (e) {}
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang, roles: dict.typed_roles } }));
}

document.addEventListener("DOMContentLoaded", () => {
  const select = document.getElementById("langSelect");
  let saved = "en";
  try { saved = localStorage.getItem("lang") || "en"; } catch (e) {}

  if (select) {
    select.value = saved;
    select.addEventListener("change", e => applyLanguage(e.target.value));
  }

  applyLanguage(saved);
});
